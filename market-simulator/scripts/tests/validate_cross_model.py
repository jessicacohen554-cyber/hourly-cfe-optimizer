def run_cross_validation(simulation_results, references=None):
    """Run cross-validation comparison against reference trajectories.

    Parameters
    ----------
    simulation_results : dict
        Pre-computed results, structured as:
        {
            'scenarios': {
                'CV_Reference_Zero_Carbon': {
                    'national': {2030: {'clean_share_pct': X, ...}, ...},
                    'by_iso': {
                        'CAISO': {2030: {...}, ...},
                        ...
                    }
                },
                'CV_Reference_EPA_Carbon': { ... },
            }
        }
        Results are passed in — this function does NOT call run_market_simulation().
    references : dict, optional
        Reference trajectories to compare against. Defaults to ALL_REFERENCES.

    Returns
    -------
    dict : Structured comparison results with divergences per scenario × reference.
    """
    if references is None:
        references = ALL_REFERENCES

    scenarios = simulation_results.get('scenarios', {})
    comparisons = {}

    # Map scenarios to their best-match reference
    scenario_reference_pairs = [
        ('CV_Reference_Zero_Carbon', 'AEO_Reference', 'clean_share_pct'),
        ('CV_Reference_Zero_Carbon', 'REEDS_Mid', 'clean_share_pct'),
        ('CV_Reference_EPA_Carbon', 'EPA_IPM_Ref', 'coal_share_pct'),
        ('CV_Reference_High_Clean', 'REEDS_Mid', 'clean_share_pct'),
    ]

    for scenario_name, ref_name, metric in scenario_reference_pairs:
        scenario_data = scenarios.get(scenario_name)
        ref_data = references.get(ref_name)

        if scenario_data is None:
            comparisons[f"{scenario_name}_vs_{ref_name}"] = {
                'error': f'Scenario {scenario_name!r} not found in simulation results',
            }
            continue
        if ref_data is None:
            comparisons[f"{scenario_name}_vs_{ref_name}"] = {
                'error': f'Reference {ref_name!r} not found',
            }
            continue

        pair_key = f"{scenario_name}_vs_{ref_name}"

        # National-level comparison
        national_results = scenario_data.get('national', {})
        comparisons[pair_key] = {
            'national': compute_divergence_metrics(national_results, ref_data),
        }

        # Per-ISO comparison (reference is national, so divergence includes
        # the structural difference between ISO-level and national average)
        by_iso = scenario_data.get('by_iso', {})
        if by_iso:
            iso_comparisons = {}
            for iso in ISOS:
                iso_data = by_iso.get(iso, {})
                if iso_data:
                    iso_comparisons[iso] = compute_divergence_metrics(
                        iso_data, ref_data
                    )
            comparisons[pair_key]['by_iso'] = iso_comparisons

    return {
        'comparisons': comparisons,
        'references_used': list(references.keys()),
        'scenarios_evaluated': list(scenarios.keys()),
    }


def print_cross_validation_report(cv_results):
    """Print a human-readable cross-validation report."""
    comparisons = cv_results.get('comparisons', {})

    print("=" * 72)
    print("CROSS-MODEL VALIDATION REPORT")
    print("=" * 72)

    for pair_name, pair_data in comparisons.items():
        if 'error' in pair_data:
            print(f"\n{pair_name}: {pair_data['error']}")
            continue

        national = pair_data.get('national')
        if national:
            print(f"\n{format_comparison_table(national)}")

        by_iso = pair_data.get('by_iso', {})
        if by_iso:
            print(f"\n### Per-ISO Divergence (vs national reference)")
            for iso in ISOS:
                iso_div = by_iso.get(iso, {})
                mean_div = iso_div.get('mean_abs_divergence')
                if mean_div is not None:
                    print(f"  {iso:6s}: mean |Δ| = {mean_div:.1f} pp")

    print("\n" + "=" * 72)


