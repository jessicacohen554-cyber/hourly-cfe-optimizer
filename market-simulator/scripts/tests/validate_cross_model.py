def build_reference_scenario_params():
    """Return the conditions dict for a 'reference-equivalent' scenario.

    Maps to: Medium demand, Medium LCOE, Medium gas, $0 carbon price.
    This approximates the AEO Reference Case assumptions (current policy,
    no new carbon pricing) within our model's parameter space.
    """
    return {
        'name': 'CV_Reference_Zero_Carbon',
        'demand_growth': 'Medium',
        'lcoe_level': 'Medium',
        'fuel_level': 'Medium',
        'carbon_price': 0,
        'learning_rate': 'Medium',
        '45q_enabled': True,
        'queue_cap_level': 'Medium',
    }


def build_epa_scenario_params():
    """Return conditions for EPA-comparable scenario ($51/ton carbon).

    Uses EPA's social cost of carbon ($51/ton, 2020$) to approximate
    an EPA IPM-like policy environment where carbon has an implicit cost.
    """
    params = build_reference_scenario_params()
    params['name'] = 'CV_Reference_EPA_Carbon'
    params['carbon_price'] = 51
    return params


def build_high_clean_scenario_params():
    """Return conditions approximating the NREL ReEDS Mid-Case.

    ReEDS assumes cost-optimal deployment with RPS constraints, which maps
    roughly to Medium LCOE with moderate carbon pricing and faster learning.
    """
    params = build_reference_scenario_params()
    params['name'] = 'CV_Reference_High_Clean'
    params['carbon_price'] = 30  # Implicit RPS value ~ $30/ton equivalent
    params['learning_rate'] = 'Medium'
    return params


